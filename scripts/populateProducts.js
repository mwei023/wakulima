// Function to populate database (to be called from the app)
export async function populateDatabase(supabase, storeId) {
  console.log('Starting database population...');

  // First, ensure categories exist
  const categories = [...new Set(parsedProducts.map(p => p.category))];
  for (const category of categories) {
    try {
      const { error } = await supabase
        .from('categories')
        .upsert({ name: category }, { onConflict: 'name' });
      if (error) console.error(`Error creating category ${category}:`, error);
    } catch (error) {
      console.error(`Error creating category ${category}:`, error);
    }
  }

  // Then create products
  let successCount = 0;
  let errorCount = 0;

  for (const product of parsedProducts) {
    try {
      // Insert into products_master
      const { data: masterData, error: masterError } = await supabase
        .from('products_master')
        .insert({
          name: product.name,
          category: product.category,
          unit: product.unit,
          selling_price: product.selling_price,
          cost_price: product.cost_price,
          barcode: product.barcode
        })
        .select()
        .single();

      if (masterError) throw masterError;

      // Insert into store_inventory
      const { error: inventoryError } = await supabase
        .from('store_inventory')
        .insert({
          product_id: masterData.id,
          stock_quantity: product.stock_quantity,
          reorder_level: product.reorder_level,
          store_id: storeId
        });

      if (inventoryError) throw inventoryError;

      successCount++;
      if (successCount % 50 === 0) {
        console.log(`Processed ${successCount} products...`);
      }
    } catch (error) {
      console.error(`Error creating product ${product.name}:`, error);
      errorCount++;
    }
  }

  console.log(`Database population complete. Success: ${successCount}, Errors: ${errorCount}`);
  return { successCount, errorCount };
}
