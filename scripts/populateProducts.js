// Function to parse the product data
function parseProducts(data) {
  const lines = data.split('\n').map(line => line.trim()).filter(line => line);
  const products = [];
  let currentCategory = '';
  let currentProduct = null;

  for (const line of lines) {
    // Check if this is a category header (all caps)
    if (line === line.toUpperCase() && !line.includes(' ') && line.length > 3) {
      currentCategory = line.toLowerCase();
      continue;
    }

    // Check if this is a product name (contains pricing info)
    if (line.includes('+') || line.includes('=')) {
      // This is a product variant with pricing
      if (currentProduct) {
        // Parse the pricing: format like "50kg 0.33+0.21.5" or "100g 3"
        const parts = line.split(' ');
        if (parts.length >= 2) {
          const unit = parts[0];
          const pricePart = parts.slice(1).join(' ');

          // Parse selling price and cost price
          let sellingPrice = 0;
          let costPrice = 0;

          if (pricePart.includes('+')) {
            const [sell, cost] = pricePart.split('+');
            sellingPrice = parseFloat(sell.replace(/[^\d.]/g, '')) || 0;
            costPrice = parseFloat(cost.replace(/[^\d.]/g, '')) || 0;
          } else if (pricePart.includes('=')) {
            const [sell, cost] = pricePart.split('=');
            sellingPrice = parseFloat(sell.replace(/[^\d.]/g, '')) || 0;
            costPrice = parseFloat(cost.replace(/[^\d.]/g, '')) || 0;
          } else {
            sellingPrice = parseFloat(pricePart.replace(/[^\d.]/g, '')) || 0;
          }

          // Create product variant
          const productName = `${currentProduct.name} ${unit}`;
          products.push({
            name: productName,
            category: currentCategory || 'miscellaneous',
            unit: unit,
            selling_price: sellingPrice,
            cost_price: costPrice,
            stock_quantity: 100, // Default stock
            reorder_level: 10, // Default reorder level
            barcode: `${currentProduct.name.replace(/\s+/g, '')}_${unit}`.toLowerCase()
          });
        }
      }
    } else {
      // This is a product name
      currentProduct = {
        name: line,
        category: currentCategory
      };
    }
  }

  return products;
}

